/* ── 라벨 ─────────────────────────────────────────────────────────── */

/**
 * mono 라벨. 구획 뱃지와 열 머리가 쓴다.
 *
 * 라틴 전용이다. 한글에는 고정폭 글자가 없어 조용히 폴백하고 0.16em 자간만
 * 남아 낱자가 흩어진다 — 이 저장소가 여러 번 겪은 사고라 감사(scripts/
 * audit.mjs)가 '한글에 넓은 자간' 으로 잡는다. 한글이면 MONO_KR 을 쓴다.
 */
export const MONO = 'font-mono text-[0.65625rem] uppercase leading-[1.5] tracking-[0.16em]';

/**
 * 도식 안의 작은 mono 라벨.
 *
 * 10px 이다. 도식은 칸이 좁아 10.5px 이면 라벨끼리 닿는다. 본문 라벨과
 * 일부러 다르게 두는 값이라 이름을 따로 준다.
 */
export const MONO_SM = 'font-mono text-[0.625rem] uppercase leading-[1.5] tracking-[0.16em]';

/**
 * 한글 라벨.
 *
 * mono 를 걸 수 없는 자리다. 12px 인 것은 pretendard 가 같은 자리에서
 * mono 보다 작아 보이기 때문이다 — 10.5px 로 두면 라벨이 아니라 주석처럼
 * 읽힌다.
 */
/* 행간을 적어 둔다. 없으면 부모 글줄의 행간을 물려받아, 같은 라벨이 글
   안에 끼면 1.7 이나 1.8 로 서고 홀로 서면 1.5 로 선다 — 라벨 하나가 놓인
   자리에 따라 높이가 달라졌다. */
export const MONO_KR = 'font-pretendard text-[0.75rem] font-medium leading-[1.5] tracking-[0.02em]';

/* ── 본문 ───────────────────────────────────────────────────────────
 *
 * 줄바꿈은 셋이 함께 막는다.
 *
 *   break-keep    한 어절 안에서 끊지 않는다. 한글은 낱말 안에서 끊기면
 *                 읽는 사람이 두 조각을 다시 붙여 읽어야 한다.
 *   text-pretty   마지막 줄에 한 낱말만 남는 일(고아)을 브라우저가 피한다.
 *                 뒤에서 두어 줄을 다시 나눠 끝을 고르게 만든다.
 *   \u00A0·       가운뎃점 앞은 붙는 빈칸이다(각 data 파일). 그러지 않으면
 *                 'SEO ·' 에서 끊겨 다음 줄이 '· GEO' 로 시작한다.
 *
 * 행간은 크기마다 하나다. 큰 글자는 좁게, 작은 글자는 넓게 — 같은 크기가
 * 구획마다 다른 행간으로 서면 같은 층위의 글이 다른 무게로 읽힌다.
 *
 *   1rem · 0.9375rem      본문        1.8   (BODY)
 *   0.875rem · 0.8125rem  작은 본문   1.7   (BODY_S)
 *   0.75rem 이하           라벨 · 칩   1.5
 *   1rem · 1.125rem        구획 리드   1.75  (LEAD — 본문보다 크므로 더 좁다)
 *
 * 라벨의 1.5 는 한 줄로 서는 것들이다. 줄이 바뀌지 않으므로 행간이 보이지
 * 않고, 칩 높이를 정하는 값으로 쓴다.
 *
 * 아키텍처 세 장이 이 값을 쓰기 전에는 같은 14px 글이 1.5 · 1.7 · 1.75 ·
 * 1.8 네 가지로 서 있었다. 손으로 적은 조합이 canon 을 지나쳐 간 자리다 —
 * 새로 쓸 때는 BODY · BODY_S 를 부른다.
 * ───────────────────────────────────────────────────────────────── */

/**
 * 읽는 글.
 *
 * 행간 1.8 은 한글이 요구하는 값이다. break-keep 이 붙는 이유도 같다 —
 * 한글은 낱말 안에서 줄이 바뀌어도 브라우저가 막지 않는다.
 */
export const BODY =
  'font-pretendard font-light leading-[1.8] tracking-[-0.01em] text-gray-700 break-keep text-pretty';

/**
 * 작은 본문 — 카드 안, 스텝 본문.
 *
 * 행간만 1.7 로 낮춘다. 좁은 칸에서 1.8 은 줄이 성겨 카드가 부풀어 보인다.
 */
export const BODY_S =
  'font-pretendard font-light leading-[1.7] tracking-[-0.01em] text-gray-700 break-keep text-pretty';

/* ── 강조색 ────────────────────────────────────────────────────────── */

/**
 * 파랑. 모회사 사이트(ipartners.co.kr)의 강조가 #3a6dfd 다.
 *
 * 원색을 그대로 글자에 쓰지 못한다 — #FCFCFC 위에서 4.28:1, #0B0B0B 위에서
 * 4.49:1 로 둘 다 기준(4.5) 아래다. 저쪽도 파랑을 글자로는 안 쓴다(흐린
 * 빛과 선 그림뿐). 우리는 라벨 대부분이 10~12px 라 판마다 값을 따로 둔다.
 * 값은 app/globals.css 의 --color-accent* 가 정본이고 여기는 그 유틸 이름이다.
 *
 *   accent       #315dd7  밝은 판. 흰판 5.58 · 파랑 6% 판 5.13 · 12% 판 4.71
 *                         — 앰버(5.45 · 5.03 · 4.63)와 같은 곡선
 *   accent-deep  #203c8b  밝은 판의 더 진한 강조. 9.84 (구 #5C3D07 9.63)
 *   accent-lit   #93affe  어두운 판. #0B0B0B 9.16 · 네이비 8.20 (구 #F0C36B)
 */
export const ACCENT = 'text-accent';
export const ACCENT_DEEP = 'text-accent-deep';

/**
 * SVG 의 stroke·fill 과 OG 이미지(Satori)는 클래스도 CSS 변수도 못 받는다.
 * app/globals.css 의 --color-accent* 를 여기 비춘다 — 바꿀 때 둘 다 바꾼다.
 * 그 밖의 자리에서 hex 를 직접 적지 않는다: 그러면 세 번째 사본이 생긴다.
 */
export const ACCENT_HEX = '#315dd7';
export const ACCENT_DEEP_HEX = '#203c8b';
export const ACCENT_LIT_HEX = '#93affe';
/** 캔버스와 rgb() 문자열은 삼중항을 받는다. 미러에서 파생한다 — 네 번째 사본을 만들지 않는다 */
export const hexRgb = (h: string) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));

/* ── 읽는 폭 ─────────────────────────────────────────────────── */

/**
 * 한 줄에 드는 글자 수를 묶는다.
 *
 * 본문 폭을 1440 으로 넓히자 폭을 안 묶어 둔 문단이 그대로 따라 늘었다.
 * 재어 보니 구획 단서가 112자, 측정 주의가 96자였다 — 한글은 마흔 자
 * 언저리가 편하고, 예순을 넘으면 눈이 다음 줄 머리를 못 찾는다.
 *
 * rem 이 아니라 em 이다. rem 으로 묶으면 글자 크기를 올릴 때 한 줄에 드는
 * 글자 수가 줄고, 내리면 늘어난다 — 정작 지켜야 하는 것은 픽셀이 아니라
 * 글자 수다. 42em 이면 어느 크기에서도 마흔두 자쯤이다.
 */
export const MEASURE = 'max-w-[42em]';

/* ── 구획 머리 ───────────────────────────────────────────────── */

/**
 * 구획 제목.
 *
 * 아키텍처 세 장이 함께 쓴다. 본문 폭을 1440 으로 넓히면서 제목만 24/30px
 * 에 머물러, 넓어진 판 위에서 제목이 본문 한 줄처럼 눌려 보였다.
 *
 * 28 → 36 → 44px. 히어로(최대 52px)보다 낮고 본문(16~18px)보다 뚜렷하게
 * 높아, 셋을 세로로 세우면 층이 한눈에 갈린다. NX Agent 가 큰 구획 제목에
 * 쓰던 32/48px 과 견주면 한 급 아래인데, 저쪽은 구획이 아니라 장을 여는
 * 제목이라 그 자리를 비워 둔다.
 *
 * 커질수록 자간을 좁히고 행간을 붙인다 — 같은 값을 쓰면 큰 글자에서 낱자가
 * 흩어지고 줄이 성겨 보인다. -0.03em · 1.18 은 그래서 나온 값이다.
 *
 * 폭을 따로 묶지 않는다. 제목은 한 줄로 서는 것이 이 장의 규칙이라, 20em
 * 으로 묶어 두었을 때는 넉넉한 화면에서도 두 줄로 접혔다. 구획 판이 이미
 * 1344px(1440 − 좌우 여백)에서 끊으므로 묶을 것이 하나 더 있을 필요가 없다.
 *
 * 좁은 화면에서는 접힌다. 스물몇 자를 한 줄에 세우려면 글자가 읽히지 않을
 * 크기까지 내려가야 해서, 거기서는 두 줄이 맞다. 그래서 text-balance 를
 * 남긴다 — 접힐 때 두 줄의 길이가 고르다.
 */
export const H2 =
  'text-balance font-display text-[1.75rem] font-medium leading-[1.18] tracking-[-0.03em] text-[#0B0B0B] break-keep md:text-[2.25rem] lg:text-[2.75rem]';

/**
 * 구획 제목 아래 한 문단.
 *
 * 15/16px 에서 16/18px 로 올린다. 제목이 커진 만큼 받는 글도 올라가야 층이
 * 유지된다.
 *
 * 행간은 1.75 다. 본문(BODY)의 1.8 보다 붙인 것은 글자가 커졌기 때문이다 —
 * 큰 글자에 같은 비율을 주면 줄 사이가 문단으로 읽힐 만큼 벌어진다.
 */
export const LEAD =
  `${MEASURE} font-pretendard text-[1rem] font-light leading-[1.75] tracking-[-0.015em] text-gray-700 break-keep text-pretty md:text-[1.125rem]`;

/**
 * 구획 제목과 리드의 정렬 — 가운데.
 *
 * 뱃지는 왼쪽에 남는다. 셋을 통째로 가운데로 보내 봤더니 구획이 어디서
 * 시작하는지를 알려 주는 것이 아무것도 왼쪽 끝에 없어, 위 구획의 끝과
 * 이 구획의 시작이 한 덩이로 보였다. 뱃지가 왼쪽 끝에 서 있으면 그 한
 * 점이 구획의 출발선이 되고, 가운데로 온 제목은 그 아래에서 무대에 선다.
 *
 * 아래 내용은 여전히 왼쪽에서 시작한다 — 약어 셋의 7.5rem 열, 01·02·03
 * 번호 레일, 2열 격자, 카드 여섯, 다섯 단계. 뱃지가 그 선을 지키고 있어서
 * 머리와 본문이 아주 갈라지지는 않는다.
 *
 * 비워 두면 왼쪽으로 돌아간다. 부르는 쪽은 손대지 않아도 된다.
 */
export const HEAD_ALIGN = 'text-center';
/** 폭이 묶인 문단(LEAD)을 판 가운데로. HEAD_ALIGN 과 짝이다 */
export const HEAD_BOX = 'mx-auto';
